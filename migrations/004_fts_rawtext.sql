-- Лексический индекс считался по embed_text, то есть ВМЕСТЕ с обогащающим
-- заголовком. А в заголовке лежит список всех экспортов файла и слова пути,
-- одинаковые для каждого чанка файла.
--
-- Следствие: запрос с именем любого символа лексически совпадал со ВСЕМИ
-- чанками того файла, а не с одним нужным. Ветка захлёбывалась ложными
-- срабатываниями, и на замерах гибрид стабильно уступал чистому вектору.
--
-- Заголовок нужен вектору (он даёт смысловой контекст), но лексике он вреден:
-- точный поиск должен идти по коду, который реально написан в этом чанке.

DROP INDEX IF EXISTS chunks_fts;
ALTER TABLE chunks DROP COLUMN IF EXISTS tsv;

ALTER TABLE chunks
  ADD COLUMN tsv tsvector
  GENERATED ALWAYS AS (to_tsvector('simple', code_tokens(raw_text))) STORED;

CREATE INDEX chunks_fts ON chunks USING gin (tsv);
