-- Пересборка HNSW с ef_construction = 200.
--
-- Почему отдельной миграцией, а не правкой 001: 001 уже применена на
-- существующих установках, и её редактирование их не обновит. Новая установка
-- пройдёт 001 (64) и сразу 005 (200) — конечное состояние одинаково у всех.
--
-- Про причинность честно: деградацию мы наблюдали на индексе, через который
-- прошли вставка и удаление ~120k векторов двух моделей без переиндексации
-- (docs/RECALL85.md §3.0). Пересборка и смена ef_construction произошли ОДНИМ
-- действием, поэтому вклад параметра от вклада самой пересборки не отделён.
-- 200 берётся как безопасная конфигурация: сборка на 62k векторов занимает
-- минуты, а верхушка выдачи заметно ближе к точному перебору. Утверждать,
-- что виновато именно значение 64, оснований нет.
--
-- Эксплуатационное следствие, которое важнее параметра: массовое удаление
-- векторов (смена модели, gc после экспериментов) обязано завершаться
-- пересборкой индекса. Признак неблагополучия — размер индекса кратно больше
-- чем «векторов × 3 КБ»; проверка расхождения с точным перебором — `scs doctor`.

DROP INDEX IF EXISTS chunks_hnsw;

CREATE INDEX chunks_hnsw ON chunks
  USING hnsw (embedding vector_cosine_ops) WITH (m = 16, ef_construction = 200);
